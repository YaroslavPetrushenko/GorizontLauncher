export type Key = keyof typeof ru;
export type T = (key: Key, vars?: Record<string, string | number>) => string;
const dicts = { ru, en };

export function makeT(lang: Lang): T {
  const dict = dicts[lang] ?? ru;
  return (key, vars) => Object.entries(vars ?? {}).reduce((text, [k, v]) => text.replace(`{${k}}`, String(v)), dict[key] ?? ru[key]);
}

export function detectLang(): Lang {
  try { return navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en'; } catch { return 'ru'; }
}
